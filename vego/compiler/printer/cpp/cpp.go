// Package cpp prints the Vego JSON form as a C++ header and source pair.
// The output includes the hand-written runtime vg.hpp.
// That runtime supplies the Slice and Str value types, the Arena allocator, and the Go conversion and comparison helpers.
// Every function that allocates receives an Arena reference as its first parameter, "mem".
// The output holds no global state.
//
// The output goes in a namespace named after the Vego package.
// Options.Namespace renames it, which lets a target keep the plain project name for its own public header.
package cpp

import (
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/oneregex/revera/vego/compiler"
)

// failure carries a printer error out of the recursive emitters.
type failure string

func fatal(args ...any) {
	panic(failure(strings.TrimSuffix(fmt.Sprintln(args...), "\n")))
}

// catch turns a failure raised by fatal into the error result of an Emit call.
// Any other panic is a bug and keeps propagating.
func catch(err *error) {
	if r := recover(); r != nil {
		f, ok := r.(failure)
		if !ok {
			panic(r)
		}
		*err = errors.New(string(f))
	}
}

// Options selects the names that the output uses.
type Options struct {
	// HeaderName is the file name the source includes; the default is engine.hpp.
	HeaderName string
	// Namespace is the namespace of the output; the default is the Vego package name.
	Namespace string
}

// Emit prints the program as a header and a source file.
func Emit(p *compiler.Program, opts Options) (header, source string, err error) {
	defer catch(&err)
	g := &gen{p: p, hppName: "engine.hpp", ns: p.Package}
	if opts.HeaderName != "" {
		g.hppName = opts.HeaderName
	}
	if opts.Namespace != "" {
		g.ns = opts.Namespace
	}
	header, source = g.files()
	return header, source, nil
}

type gen struct {
	p       *compiler.Program
	b       strings.Builder
	fn      *compiler.FuncDecl
	tmp     int
	used    map[string]bool
	hppName string
	ns      string
}

