// Command json2cpp converts the Vego JSON form into a C++ header
// and source pair. The output includes the hand-written runtime
// vg.hpp, which supplies the Slice and Str value types, the Arena
// allocator, and the Go conversion and comparison helpers. Every
// function that allocates receives an Arena reference as its first
// parameter, "mem"; the output holds no global state.
//
// Usage:
//
//	json2cpp [-hpp engine.hpp] [-cpp engine.cpp] input.json
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"revera1/vegoc"
)

func fatal(args ...any) {
	fmt.Fprintln(os.Stderr, args...)
	os.Exit(1)
}

func main() {
	hpp := flag.String("hpp", "", "output header (default stdout)")
	cpp := flag.String("cpp", "", "output source (default stdout)")
	flag.Parse()
	if flag.NArg() != 1 {
		fatal("usage: json2cpp [-hpp engine.hpp] [-cpp engine.cpp] input.json")
	}
	p, err := vegoc.LoadFile(flag.Arg(0))
	if err != nil {
		fatal(err)
	}
	g := &gen{p: p, hppName: "engine.hpp"}
	if *hpp != "" {
		g.hppName = filepath.Base(*hpp)
	}
	header, source := g.files()
	write := func(path, text string) {
		if path == "" {
			os.Stdout.WriteString(text)
			return
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			fatal(err)
		}
	}
	write(*hpp, header)
	write(*cpp, source)
}

type gen struct {
	p       *vegoc.Program
	b       strings.Builder
	fn      *vegoc.FuncDecl
	tmp     int
	hppName string
}

